#!/usr/bin/env python3
"""Generate config/provider_limits.yaml from llm_providers.db.

The router already knows how to enforce RPM, daily requests, and daily token
caps, but config/provider_caps.yaml historically left those values at 0
("unknown"). This script fills that gap from the verified free-tier numbers in
llm-provider-manager/llm_providers.db.

Run after the database changes:

    python scripts/generate_provider_limits.py
    python scripts/generate_provider_limits.py --check

The generated file is a low-priority overlay. Values in router_config.yaml's
per-provider rate_limits, model_overrides, or candidate conditions still win.
"""

from __future__ import annotations

import argparse
import os
import sqlite3
import sys
import tempfile
from pathlib import Path
from typing import Dict

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = REPO_ROOT.parent / "llm-provider-manager" / "llm_providers.db"
DEFAULT_OUT = REPO_ROOT / "config" / "provider_limits.yaml"

# Database key_name -> router_config.yaml provider key. Only include names that
# differ; exact matches need no entry.
ALIASES = {
    "blazeai": "blaze-free",
}

HEADER = """\
# Generated by scripts/generate_provider_limits.py -- do not edit by hand.
# Source: llm-provider-manager/llm_providers.db
#
# Lowest-priority rate-limit defaults for RouterCore._compute_rate_limits().
# router_config.yaml rate_limits, model_overrides, and candidate conditions
# override these values. 0 / missing means unknown and is not emitted.
"""


def load_limits(db_path: Path) -> Dict[str, Dict[str, int]]:
    """Return {provider: {rpm, daily_tokens}} for positive per-provider limits."""
    if not db_path.exists():
        raise FileNotFoundError(f"provider database not found: {db_path}")

    limits: Dict[str, Dict[str, int]] = {}
    with sqlite3.connect(str(db_path)) as conn:
        rows = conn.execute(
            """
            SELECT key_name, rate_limit_rpm, rate_limit_daily_tokens
            FROM providers
            WHERE COALESCE(rate_limit_rpm, 0) > 0
               OR COALESCE(rate_limit_daily_tokens, 0) > 0
            """
        ).fetchall()

    for key_name, rpm, daily_tokens in rows:
        if not key_name:
            continue
        provider = ALIASES.get(str(key_name), str(key_name))
        entry = limits.setdefault(provider, {})
        if rpm is not None and int(rpm) > 0:
            entry["rpm"] = max(entry.get("rpm", 0), int(rpm))
        if daily_tokens is not None and int(daily_tokens) > 0:
            entry["daily_tokens"] = max(
                entry.get("daily_tokens", 0), int(daily_tokens)
            )

    return dict(sorted(limits.items()))


def render(limits: Dict[str, Dict[str, int]]) -> str:
    """Render the YAML overlay with a stable, readable header."""
    body = yaml.safe_dump(
        {"providers": limits},
        sort_keys=True,
        default_flow_style=False,
        allow_unicode=False,
    )
    return HEADER + body


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=str(path.parent), prefix=f".{path.name}.", suffix=".tmp"
    )
    try:
        with os.fdopen(fd, "w", encoding="ascii") as handle:
            handle.write(text)
        os.replace(tmp_name, path)
    finally:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--db",
        type=Path,
        default=DEFAULT_DB,
        help=f"provider SQLite database (default: {DEFAULT_DB})",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT,
        help=f"output YAML path (default: {DEFAULT_OUT})",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the output file is missing or out of date",
    )
    args = parser.parse_args()

    try:
        text = render(load_limits(args.db))
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not args.out.exists():
            print(f"out of date: {args.out} is missing", file=sys.stderr)
            return 1
        if args.out.read_text(encoding="ascii") != text:
            print(f"out of date: {args.out} needs regeneration", file=sys.stderr)
            return 1
        print(f"up to date: {args.out}")
        return 0

    atomic_write(args.out, text)
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
