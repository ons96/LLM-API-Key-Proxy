#!/usr/bin/env python3
"""Wire authenticated g4f access into the LLM-API-Key-Proxy gateway.

Idempotent. Two edits, both asserted:
  1. router_config.yaml : g4f* blocks -> no_api_key_required: false (use the key)
  2. catalog.json.gz    : g4f* providers -> fully_free / quota_tier 0 / models is_free

The catalog is generated by llm-provider-manager's build_gateway_catalog.py,
which is not present in this checkout, so the artifact is patched directly.
Rerun this script after any catalog regeneration.
"""
import gzip
import json
import re
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
G4F_IDS = ["g4f", "g4f_gemini", "g4f_groq", "g4f_nvidia", "g4f_ollama", "g4f_pollinations"]
REASON = (
    "free with a g4f.dev account key: signed-in callers skip the cake-credit "
    "gate and get tier 'free' = 500 req/day + 5M tokens/day (USER_TIER_LIMITS "
    "in workers/api-worker.js). Verified 2026-11-02 with a live key."
)

router_cfg = ROOT / "config/router_config.yaml"
catalog = ROOT / "config/catalog.json.gz"
ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")

# ---------- 1. router_config.yaml ----------
text = router_cfg.read_text()
shutil.copy2(router_cfg, router_cfg.with_name(router_cfg.name + f".bak.pre-g4f-key-{ts}"))

lines = text.splitlines(keepends=True)
changed, out, i = [], [], 0
while i < len(lines):
    m = re.match(r"^  ([A-Za-z0-9_]+):\s*$", lines[i])
    if m and m.group(1) in G4F_IDS:
        pid = m.group(1)
        out.append(lines[i])
        i += 1
        while i < len(lines) and not re.match(r"^  [A-Za-z0-9_]+:\s*$", lines[i]) and not re.match(r"^[A-Za-z]", lines[i]):
            if re.match(r"^    no_api_key_required:\s*true\s*$", lines[i]):
                out.append("    no_api_key_required: false\n")
                changed.append(pid)
            else:
                out.append(lines[i])
            i += 1
        continue
    out.append(lines[i])
    i += 1

assert len(set(changed)) <= len(G4F_IDS), changed
router_cfg.write_text("".join(out))
print(f"router_config: flipped no_api_key_required -> false for {sorted(set(changed))}")

# ---------- 2. catalog.json.gz ----------
shutil.copy2(catalog, catalog.with_name(catalog.name + f".bak.pre-g4f-key-{ts}"))
data = json.loads(gzip.open(catalog, "rt", encoding="utf-8").read())
hit = []
for prov in data["providers"]:
    if prov.get("provider_id") not in G4F_IDS:
        continue
    prov["provider_type"] = "fully_free"
    prov["quota_tier"] = 0
    prov["confidence"] = "high"
    prov["classification_rung"] = "human"
    prov["classification_reason"] = REASON
    prov["last_verified"] = "2026-11-02"
    for m in prov.get("models") or []:
        m["is_free"] = True
    hit.append(prov["provider_id"])
missing = [p for p in G4F_IDS if p not in hit]
assert not missing, f"catalog missing providers: {missing}"

data["generated_at"] = data.get("generated_at")
with gzip.open(catalog, "wt", encoding="utf-8", compresslevel=9) as fh:
    json.dump(data, fh, separators=(",", ":"))
print(f"catalog: reclassified {sorted(hit)} -> fully_free / tier 0")

# ---------- 3. verify through the gateway's own policy module ----------
root = str(ROOT.resolve())
sys.path.insert(0, root); sys.path.insert(0, root + "/src")
from proxy_app.routing.free_policy import load_tiers, model_is_free, provider_type  # noqa: E402

cache = load_tiers(root, force=True)
ok = True
for pid in G4F_IDS:
    t, pt = cache.get(pid), provider_type(cache, pid)
    if t != 0 or pt != "fully_free":
        ok = False
        print(f"  FAIL {pid}: tier={t} type={pt}")
print("free_policy:", "OK all six tier 0 / fully_free" if ok else "MISMATCH")
sys.exit(0 if ok else 1)
